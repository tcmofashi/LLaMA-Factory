
#!/usr/bin/env python3
"""
Prompt模板用于ReAct Agent生成问题和回答
"""

# ============================================================================
# 生成问题的Prompt模板
# ============================================================================

QUESTION_GENERATION_TEMPLATE = """请基于萌娘百科中关于'{anime_name}'的详细条目信息，生成5个问题。要求：

1）前3个问题是事实性问题，但需要集成多个信息点（例如：
   - 问题1：将播出时间、导演、制作公司等基础信息整合为一个问题
   - 问题2：将主要角色及其声优、乐器担当/职位整合为一个问题
   - 问题3：将剧情设定和关键背景整合为一个问题

2）第4个问题是内容概括类问题，要求概括作品的核心内容和情节发展

3）第5个问题是主旨和艺术分析类问题，探讨作品的主题思想和艺术表现手法

4）题目中可以包含背景信息，但不能包含答案

5）问题要具有一定的综合性和深度，适合用于评估模型的理解能力

请直接输出5个问题，每个问题单独一行。"""


# ============================================================================
# 回答问题的Prompt模板（教师模式）
# ============================================================================

ANSWER_GENERATION_TEMPLATE = """请回答以下问题：{question}

要求：

1）首先使用萌娘百科工具全面搜索'{anime_name}'的详细信息

2）将从百科搜索到的所有相关信息（包括基本信息、制作背景、人物设定、剧情内容、音乐信息等）自然地表述为你自己已经掌握的完整知识体系

3）回答应该以自然段落的形式组织，直接呈现内容，不要使用"知识说明"、"问题回答"等标题或结构化标记

4）表述应该让读者感觉这些信息是你本来就了解和掌握的，而不是通过搜索或查询获得的

5）内容应该全面且有层次，包括作品的多个方面，每个方面用一段话阐述

6）回答要有条理性和深度，体现出对作品的深入理解
"""


# ============================================================================
# 简化版回答模板（用于快速生成）
# ============================================================================

SIMPLE_ANSWER_TEMPLATE = """请使用萌娘百科工具搜索'{anime_name}'的信息，然后回答：{question}

要求：
1）首先搜索萌娘百科获取详细信息
2）回答时请先说明你已知的信息
3）然后用'根据我的了解'开头给出答案
4）不要暴露搜索迹象，使用'据我所知'等内生化表述
"""


# ============================================================================
# 使用示例
# ============================================================================

if __name__ == "__main__":
    # 示例：为《莉兹与青鸟》生成问题
    anime = "莉兹与青鸟"
    prompt = QUESTION_GENERATION_TEMPLATE.format(anime_name=anime)
    print("=== 问题生成Prompt ===")
    print(prompt)
    print("\n" + "="*80 + "\n")

    # 示例：回答第一个问题
    question = """由山田尚子执导、吉田玲子编剧、京都动画制作、松竹发行、片长90分钟的动画电影《莉兹与青鸟》于2018年4月21日在日本上映，这部作品改编自武田绫乃的哪部小说，与《吹响！上低音号》有何关联？"""

    answer_prompt = ANSWER_GENERATION_TEMPLATE.format(
        anime_name=anime,
        question=question
    )
    print("=== 回答生成Prompt ===")
    print(answer_prompt)
